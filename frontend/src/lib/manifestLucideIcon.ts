/** Every icon name an App manifest may use. Kept equal to `backend/app/services/manifest_icons.py`. */
export const MANIFEST_ICON_IDS: string[] = Object.keys(MANIFEST_ICON_BY_ID).sort();

function normalizeIconId(raw: string): string {
  return raw.trim().toLowerCase().replace(/_/g, '-');
}

export function lucideFromOperationalModelIcon(raw?: string | null): LucideIcon {
  if (raw == null || typeof raw !== 'string') return FileText;
  const k = normalizeIconId(raw);
  if (!k) return FileText;
  return MANIFEST_ICON_BY_ID[k] ?? FileText;
}

/** The icon for a name in the fixed list, or ``undefined`` for a name that is not in it (no silent fallback). */
export function knownManifestIcon(raw?: string | null): LucideIcon | undefined {
  if (!raw || typeof raw !== 'string') return undefined;
  const k = normalizeIconId(raw);
  return Object.prototype.hasOwnProperty.call(MANIFEST_ICON_BY_ID, k) ? MANIFEST_ICON_BY_ID[k] : undefined;
}
