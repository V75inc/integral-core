"""Fresh-install provisioning of the release-reviewed catalog before serving."""

import json
import os
from pathlib import Path
from urllib.parse import quote, urlsplit, urlunsplit

from jvspatial.db.indexes import identifier as q

from .catalog import build_catalog
from .lifecycle import PlanError, apply, plan
from .runtime import inspect


def serving_dsn(migration_dsn, role, password):
    """Derive a runtime-only login while preserving the database endpoint."""
    parsed = urlsplit(migration_dsn)
    host = parsed.hostname or "localhost"
    if ":" in host:
        host = "[" + host + "]"
    return urlunsplit(
        parsed._replace(
            netloc=f"{quote(role, safe='')}:{quote(password, safe='')}@{host}:{parsed.port or 5432}"
        )
    )


async def initial_install(dsn, *, runtime_role, runtime_password, plan_path):
    """Only an empty DB or the exact saved initial plan may be provisioned.

    Existing populated installations require an explicit reviewed operator plan;
    startup never generates an automatic replacement plan for them.
    """
    import asyncpg

    conn = await asyncpg.connect(dsn)
    try:
        path = Path(plan_path)
        saved = json.loads(path.read_text()) if path.exists() else None
        # Select one of the release-reviewed initial profiles. A missing optional
        # extension remains degraded; its later installation never triggers DDL.
        include_search = (
            saved["include_search"]
            if saved
            else bool(
                await conn.fetchval(
                    "SELECT 1 FROM pg_available_extensions WHERE name='vector'"
                )
            )
        )
        specs = build_catalog(include_search=include_search)
        existing = await conn.fetchval(
            "SELECT to_regclass('public.integral_index_catalog')"
        )
        if existing:
            status = await inspect(conn, specs)
            if status["ready"]:
                runtime = serving_dsn(dsn, runtime_role, runtime_password)
                serving = await asyncpg.connect(runtime)
                try:
                    readiness = await inspect(serving, specs, enforce_runtime_role=True)
                    if not readiness["ready"]:
                        raise PlanError("Existing runtime role is not ready")
                finally:
                    await serving.close()
                return runtime
        if saved:
            artifact = saved
        else:
            occupied = await conn.fetchval(
                "SELECT EXISTS(SELECT 1 FROM pg_tables WHERE schemaname='public')"
            )
            if occupied:
                raise PlanError(
                    "Existing storage requires reviewed indexes plan/apply before managed startup"
                )
            artifact = await plan(
                conn,
                specs,
                max_indexes=len(specs) + 16,
                max_index_bytes=2_000_000_000,
                max_build_bytes=3_000_000_000,
                runtime_role=runtime_role,
                include_search=include_search,
            )
            path.parent.mkdir(parents=True, exist_ok=True)
            fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
            with os.fdopen(fd, "w") as stream:
                json.dump(artifact, stream, indent=2)
        if not await conn.fetchval(
            "SELECT 1 FROM pg_roles WHERE rolname=$1", runtime_role
        ):
            # Password is generated by the installer, never retained in a plan.
            if not isinstance(runtime_password, str) or len(runtime_password) < 24:
                raise PlanError("A generated runtime credential is required")
            secret = "'" + runtime_password.replace("'", "''") + "'"
            await conn.execute(
                f"CREATE ROLE {q(runtime_role)} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD {secret}"
            )
        await apply(
            conn, artifact, approved_hash=artifact["hash"], expected_specs=specs
        )
        return serving_dsn(dsn, runtime_role, runtime_password)
    finally:
        await conn.close()


async def _main():
    """One-off maintenance entrypoint; serving processes never invoke this."""
    from .commands import connection_dsn

    dsn = connection_dsn(migration=True)
    reviewed = os.getenv("INTEGRAL_INDEX_PLAN_PATH")
    if reviewed:
        import asyncpg

        artifact = json.loads(Path(reviewed).read_text())
        conn = await asyncpg.connect(dsn)
        try:
            await apply(
                conn,
                artifact,
                approved_hash=os.environ["INDEX_PLAN_APPROVED_HASH"],
                expected_specs=build_catalog(),
            )
        finally:
            await conn.close()
    else:
        await initial_install(
            dsn,
            runtime_role=os.environ["INTEGRAL_RUNTIME_POSTGRES_USER"],
            runtime_password=os.environ["INTEGRAL_RUNTIME_POSTGRES_PASSWORD"],
            plan_path=os.environ["INTEGRAL_INITIAL_INDEX_PLAN_PATH"],
        )
    print("Managed storage provisioning completed")


if __name__ == "__main__":
    import asyncio

    asyncio.run(_main())
