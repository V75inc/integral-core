# Process-shared source cache; never contains caller access decisions.
_CACHED_LIBRARY_SPECS: Optional[
    tuple[Sequence[LibraryProfileSpec], Sequence[ProfileLoadIssue]]
] = None
_CACHED_PROFILES_ROOT: Optional[Any] = None
_LIBRARY_CACHE_LOCK = threading.RLock()


# The source key below runs on every cached library read, under a global lock.
# It used ``sorted(root.glob("*/*"))`` and ``sorted(path.rglob("*"))``, which
# built a Path object per file and compared them part by part (about 0.25 s
# for 1,229 files; most of it in globbing, not in the stat calls). These
# helpers list the same entries with ``os.scandir`` and plain strings, in the
# same order, so the key is identical; tests/test_library_source_walk.py
# checks that against the pathlib walk, symlinks included.


def _sorted_paths(paths: List[str]) -> List[str]:
    """Order like ``sorted()`` over Path objects: by path parts, not raw string."""
    return sorted(paths, key=lambda p: p.split(os.sep))


def _package_entries(root: Path) -> List[str]:
    """Same entries as ``root.glob("*/*")``: children of each directory in root."""
    out: List[str] = []
    try:
        with os.scandir(root) as it:
            top = list(it)
    except OSError:
        return out
    for entry in top:
        try:
            if not entry.is_dir():  # follows symlinks, like the glob
                continue
        except OSError:
            continue
        parent = str(root / entry.name)
        try:
            with os.scandir(parent) as it:
                out.extend(os.path.join(parent, child.name) for child in it)
        except OSError:
            continue
    return out


def _tree_entries(top: str) -> List[str]:
    """Same entries as ``Path(top).rglob("*")``.

    Every entry below ``top``, descending real directories only: a symlink to
    a directory is listed but not entered, as pathlib's walk does.
    """
    out: List[str] = []
    pending = [top]
    while pending:
        current = pending.pop()
        try:
            with os.scandir(current) as it:
                entries = list(it)
        except OSError:
            continue
        for entry in entries:
            out.append(entry.path)
            try:
                if entry.is_dir(follow_symlinks=False):
                    pending.append(entry.path)
            except OSError:
                continue
    return out


def _library_source_key() -> tuple:
    """Watch source metadata, never workspace content or permission decisions.

    Include every bundle artifact covered by signature verification. ctime and
    inode detect same-size replacements even when a publisher preserves mtime.
    This disk walk runs off the event loop for resident callers.
    """
    from app.services import operational_model_field_types as fields
    from app.services import operational_model_loader as loader
    from app.services import operational_model_wizard_steps as steps
    from app.services.package_paths import is_core_only_mode, resolve_package_paths
    from app.views import operational_model_view_types as views

    roots = (
        [Path(loader._PROFILES_ROOT)]
        if Path(loader._PROFILES_ROOT)
        != Path(loader.__file__).parent.parent / "packages"
        else resolve_package_paths()
    )
    artifacts = []
    for root in roots:
        artifacts.append((str(root.resolve()), root.exists()))
        for path in _sorted_paths(_package_entries(root)):
            # Descend package trees, including directories so removing the last
            # file or adding a new skill invalidates a previously empty package.
            paths = (
                [path, *_sorted_paths(_tree_entries(path))]
                if os.path.isdir(path)
                else [path]
            )
            for item in paths:
                # Signature verification currently covers generated bytecode too.
                # Match that trust boundary even though the install fingerprint
                # omits __pycache__; warm reuse must never hide a rejected source.
                stat = os.stat(item)
                artifacts.append(
                    (
                        item,
                        os.path.realpath(item),
                        stat.st_ino,
                        stat.st_size,
                        stat.st_mtime_ns,
                        stat.st_ctime_ns,
                    )
                )
    return (
        tuple(artifacts),
        is_core_only_mode(),
        os.environ.get("INTEGRAL_OPERATIONAL_MODEL_PUBKEY", ""),
        os.environ.get("INTEGRAL_PLUGIN_PUBKEY", ""),
        fields.registry_version(),
        views.registry_version(),
        tuple(
            (name, repr(spec)) for name, spec in sorted(steps.list_step_kinds().items())
        ),
    )


def load_library_operational_models_with_issues_cached() -> (
    tuple[Sequence[LibraryProfileSpec], Sequence[ProfileLoadIssue]]
):
    """Reuse validated library specs until artifacts, trust or registries change.

    Resident callers use a worker thread; concurrent cold callers share one
    validation. Failed or unstable refreshes never return older source specs.
    """
    global _CACHED_LIBRARY_SPECS, _CACHED_PROFILES_ROOT
    with _LIBRARY_CACHE_LOCK:
        for _attempt in range(2):
            cache_key = _library_source_key()
            if _CACHED_LIBRARY_SPECS is not None and _CACHED_PROFILES_ROOT == cache_key:
                return _CACHED_LIBRARY_SPECS
            loaded = load_library_operational_models_with_issues()
            if _library_source_key() == cache_key:
                _CACHED_LIBRARY_SPECS = loaded
                _CACHED_PROFILES_ROOT = cache_key
                return loaded
        # Never publish a mixture of artifacts from a concurrent package update.
        _CACHED_LIBRARY_SPECS = None
        _CACHED_PROFILES_ROOT = None
        raise RuntimeError("Library artifacts changed during validation")


def load_library_bundle_index() -> tuple[str, Dict[str, LibraryProfileSpec]]:
    """One bounded cached validation result shared by all Apps in a turn."""
    with _LIBRARY_CACHE_LOCK:
        specs, _issues = load_library_operational_models_with_issues_cached()
        fingerprint = hashlib.sha256(repr(_CACHED_PROFILES_ROOT).encode()).hexdigest()
        return fingerprint, {spec.slug: spec for spec in specs if spec.slug}


# Coalesce concurrent requests before entering the executor. A threading lock
# alone would park one default-pool thread per caller behind a cold catalogue.
_LIBRARY_LOAD_TASKS: WeakKeyDictionary = WeakKeyDictionary()


def _load_library_snapshot() -> tuple:
    with _LIBRARY_CACHE_LOCK:
        specs, issues = load_library_operational_models_with_issues_cached()
        token = hashlib.sha256(repr(_CACHED_PROFILES_ROOT).encode()).hexdigest()
        return token, specs, issues


async def load_library_snapshot() -> tuple:
    """Read a fresh validated source snapshot off-loop, singleflight per loop.

    Only overlapping reads share work. The next request checks source/trust
    freshness again. Cancellation of one waiter cannot cancel another's load.
    This carries source metadata only; caller authority is never cached here.
    """
    loop = asyncio.get_running_loop()
    task = _LIBRARY_LOAD_TASKS.get(loop)
    if task is None or task.done():
        task = loop.create_task(asyncio.to_thread(_load_library_snapshot))
        _LIBRARY_LOAD_TASKS[loop] = task

        def finished(done: asyncio.Task) -> None:
            if _LIBRARY_LOAD_TASKS.get(loop) is done:
                del _LIBRARY_LOAD_TASKS[loop]
            if not done.cancelled():
                done.exception()  # Observe failures even when every waiter left.

        task.add_done_callback(finished)
    return await asyncio.shield(task)


async def load_library_bundle_index_async() -> (
    tuple[str, Dict[str, LibraryProfileSpec]]
):
    """Index the shared off-loop source snapshot by declared bundle slug."""
    token, specs, _issues = await load_library_snapshot()
    return token, {spec.slug: spec for spec in specs if spec.slug}


def reset_library_operational_models_cache_for_testing() -> None:
    """Clear the session cache (tests that monkeypatch ``_PROFILES_ROOT``)."""
    global _CACHED_LIBRARY_SPECS, _CACHED_PROFILES_ROOT
    with _LIBRARY_CACHE_LOCK:
        _CACHED_LIBRARY_SPECS = None
        _CACHED_PROFILES_ROOT = None
    from app.services.operational_model_compile import reset_seeded_library_view_index

    reset_seeded_library_view_index()


async def _is_library_operational_model_referenced(operational_model_id: str) -> bool:
    tracks = await Track.find({"context.library_merge_source_id": operational_model_id})
    if tracks:
        return True
    apps = await App.find({"context.library_merge_source_id": operational_model_id})
    return bool(apps)


async def _deactivate_removed_seeded_profile(
    cp: OperationalModel,
    *,
    now_iso: str,
    reason: str,
) -> str:
    md = dict(cp.metadata or {})
    md["seed_status"] = "inactive"
    md["seed_removed_at"] = now_iso
    md["seed_removed_reason"] = reason
    cp.metadata = md
    cp.library_package = False
    cp.updated_at = now_iso
    await cp.save()
    return "deactivated"


async def reconcile_removed_seeded_packages(
    *,
    removed_slugs: Sequence[str],
    now_iso: str,
) -> List[Dict[str, Any]]:
    """Deactivate platform-seeded catalog rows no longer present on disk."""
    outcomes: List[Dict[str, Any]] = []
    for slug in removed_slugs:
        rows = await OperationalModel.find(
            {
                "context.library_package": True,
                "context.metadata.slug": slug,
                "context.metadata.seed_status": "active",
            }
        )
        if rows is None:
            matches: List[OperationalModel] = []
        elif isinstance(rows, list):
            matches = rows
        else:
            matches = [rows]
        for cp in matches:
            current = await platform_seed_model(cp.id)
            if current is None:
                outcomes.append(
                    {
                        "slug": slug,
                        "operational_model_id": cp.id,
                        "status": "skipped_unproven_publication",
                    }
                )
                continue
            cp = current
            if not cp.library_package or (cp.metadata or {}).get("slug") != slug:
                continue
            referenced = await _is_library_operational_model_referenced(cp.id)
            status = await _deactivate_removed_seeded_profile(
                cp,
                now_iso=now_iso,
                reason="bundle_missing_referenced" if referenced else "bundle_missing",
            )
            outcomes.append(
                {
                    "slug": slug,
                    "operational_model_id": cp.id,
                    "status": status,
                    "referenced": referenced,
                }
            )
    return outcomes


def _load_library_specs_for_sync(*, use_cached_specs: bool) -> tuple:
    """Serialize catalogue compilation with resident source refreshes."""
    with _LIBRARY_CACHE_LOCK:
        if use_cached_specs:
            return load_library_operational_models_with_issues_cached()
        return load_library_operational_models_with_issues()


async def sync_library_catalog_from_disk(
    *,
    catalog_registry: Any,
    ensure_catalog_edge: Callable[[Any, Any], Awaitable[None]],
    previous_index: Optional[Dict[str, Dict[str, Any]]] = None,
    now_iso: Optional[str] = None,
    use_cached_specs: bool = False,
) -> Dict[str, Any]:
    """Sync disk bundles into catalog and reconcile removed seeded rows."""
    stamp = now_iso or datetime.now(timezone.utc).isoformat()
    specs, issues = await asyncio.to_thread(
        _load_library_specs_for_sync, use_cached_specs=use_cached_specs
    )
    now_index: Dict[str, Dict[str, Any]] = {
        s.slug: {"bundle_fingerprint": s.bundle_fingerprint, "version": s.version}
        for s in specs
        if s.slug
    }
    prior = previous_index or {}
    if not prior:
        added = sorted(now_index.keys())
        updated: List[str] = []
        upsert_specs: Sequence[LibraryProfileSpec] = specs
    else:
        added = sorted([slug for slug in now_index if slug not in prior])
        updated = sorted(
            [
                slug
                for slug in now_index
                if slug in prior
                and prior.get(slug, {}).get("bundle_fingerprint")
                != now_index[slug]["bundle_fingerprint"]
            ]
        )
        changed = set(added + updated)
        upsert_specs = [s for s in specs if s.slug in changed]

    # The process-local index is only a rescan optimization. Startup must
    # reconcile packages removed while this process was stopped as well.
    seeded_rows = await OperationalModel.find(
        {
            "context.library_package": True,
            "context.metadata.seed_status": "active",
        }
    )
    persisted_slugs = set()
    for row in seeded_rows or []:
        current = await platform_seed_model(row.id)
        if current is not None and current.library_package:
            slug = (current.metadata or {}).get("slug")
            if isinstance(slug, str) and slug:
                persisted_slugs.add(slug)
    removed = sorted((set(prior) | persisted_slugs) - set(now_index))

    if upsert_specs:
        await upsert_seeded_library_packages(
            catalog_registry=catalog_registry,
            specs=upsert_specs,
            now_iso=stamp,
            ensure_catalog_edge=ensure_catalog_edge,
        )
    reconciled_removed = await reconcile_removed_seeded_packages(
        removed_slugs=removed,
        now_iso=stamp,
    )
    return {
        "added": added,
        "updated": updated,
        "removed": removed,
        "issues": issues,
        "index": now_index,
        "reconciled_removed": reconciled_removed,
    }
