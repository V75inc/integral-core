def normalize_manifest_icon(value: object, *, where: str) -> str:
    """Return a valid icon name, or "" when none was given; refuse a name outside the list."""
    raw = str(value or "").strip().lower().replace("_", "-")
    if not raw:
        return ""
    if raw not in MANIFEST_ICON_KEYS:
        raise BadRequestError(
            message=f"{where}.icon '{raw}' is not one of Integral's icons. Choose one of: "
            + ", ".join(sorted(MANIFEST_ICON_KEYS))
        )
    return raw
